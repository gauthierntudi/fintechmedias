function sqlValue(v: unknown): string {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "boolean") return v ? "1" : "0";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) return "NULL";
    return String(v);
  }
  if (v instanceof Date) return `'${v.toISOString().replace(/'/g, "''")}'`;
  if (typeof v === "bigint") return String(v);
  if (typeof v === "object") {
    return `'${JSON.stringify(v).replace(/'/g, "''")}'`;
  }
  return `'${String(v).replace(/'/g, "''")}'`;
}

function insertSql(table: string, row: Record<string, unknown>): string {
  const cols = Object.keys(row);
  const colList = cols.map((c) => `"${c}"`).join(", ");
  const vals = cols.map((c) => sqlValue(row[c])).join(", ");
  return `INSERT OR REPLACE INTO "${table}" (${colList}) VALUES (${vals});`;
}

async function main() {
  const lines: string[] = [
    "-- Generated by apps/api/scripts/export-pg-to-d1.ts",
    // D1 remote refuse BEGIN/COMMIT SQL — wrangler wrappe déjà en transaction.
    "PRAGMA defer_foreign_keys=ON;",
  ];

  let total = 0;
  for (const { table, fetch } of EXPORTS) {
    const rows = await fetch();
    lines.push(`-- ${table}: ${rows.length}`);
    for (const row of rows) {
      lines.push(insertSql(table, row));
    }
    total += rows.length;
    console.log(`${table.padEnd(28)} ${rows.length}`);
  }

  lines.push("PRAGMA defer_foreign_keys=OFF;");

  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, `${lines.join("\n")}\n`, "utf8");
  console.log(`\n→ ${OUT}`);
  console.log(`Total rows: ${total}`);
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
